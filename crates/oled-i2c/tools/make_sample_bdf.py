#!/usr/bin/env python3
"""Generate a sample `FONT.BDF` for the Dasai Mochi SD card.

This writes a small 5x7 uppercase bitmap font (A-Z plus space) — the same
shapes as the built-in `FONT_5X7` — as a valid BDF file. Drop it on the SD
card root as `FONT.BDF` and the firmware will load it at boot and render the
"DASAI MOCHI" banner with it (see `src/dasai.rs::try_load_font`).

Usages:
    python3 make_sample_bdf.py > /media/your_card/FONT.BDF
    or (no redirection) to print to stdout:
    python3 make_sample_bdf.py

You can also hand it any other BDF font; the loader accepts whatever it
contains (up to its bitmap/span capacity).
"""

# Classic 5x7 glyphs (row-major, bit7 = leftmost pixel), identical to the
# Adafruit GFX glcdfont used for the built-in `FONT_5X7`.
GLYPHS: dict[str, list[int]] = {
    " ": [0x00] * 7,
    "A": [0x70, 0x88, 0x88, 0xF8, 0x88, 0x88, 0x88],
    "B": [0xF0, 0x88, 0x88, 0xF0, 0x88, 0x88, 0xF0],
    "C": [0x70, 0x88, 0x80, 0x80, 0x80, 0x88, 0x70],
    "D": [0xF0, 0x88, 0x88, 0x88, 0x88, 0x88, 0xF0],
    "E": [0xF8, 0x80, 0x80, 0xF0, 0x80, 0x80, 0xF8],
    "F": [0xF8, 0x80, 0x80, 0xF0, 0x80, 0x80, 0x80],
    "G": [0x70, 0x88, 0x80, 0x80, 0x98, 0x88, 0x78],
    "H": [0x88, 0x88, 0x88, 0xF8, 0x88, 0x88, 0x88],
    "I": [0x70, 0x20, 0x20, 0x20, 0x20, 0x20, 0x70],
    "J": [0x38, 0x10, 0x10, 0x10, 0x10, 0x90, 0x60],
    "K": [0x88, 0x90, 0xA0, 0xC0, 0xA0, 0x90, 0x88],
    "L": [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xF8],
    "M": [0x88, 0xD8, 0xA8, 0xA8, 0xA8, 0x88, 0x88],
    "N": [0x88, 0x88, 0xC8, 0xA8, 0x98, 0x88, 0x88],
    "O": [0x70, 0x88, 0x88, 0x88, 0x88, 0x88, 0x70],
    "P": [0xF0, 0x88, 0x88, 0xF0, 0x80, 0x80, 0x80],
    "Q": [0x70, 0x88, 0x88, 0x88, 0xA8, 0x90, 0x68],
    "R": [0xF0, 0x88, 0x88, 0xF0, 0xA0, 0x90, 0x88],
    "S": [0x78, 0x80, 0x80, 0x70, 0x08, 0x08, 0xF0],
    "T": [0xF8, 0xA8, 0x20, 0x20, 0x20, 0x20, 0x20],
    "U": [0x88, 0x88, 0x88, 0x88, 0x88, 0x88, 0x70],
    "V": [0x88, 0x88, 0x88, 0x88, 0x50, 0x50, 0x20],
    "W": [0x88, 0x88, 0xA8, 0xA8, 0xA8, 0xA8, 0x50],
    "X": [0x88, 0x88, 0x50, 0x20, 0x50, 0x88, 0x88],
    "Y": [0x88, 0x88, 0x50, 0x20, 0x20, 0x20, 0x20],
    "Z": [0xF8, 0x08, 0x10, 0x20, 0x40, 0x80, 0xF8],
}


def emit_bdf() -> list[str]:
    out: list[str] = []
    out.append("STARTFONT 2.1")
    out.append("FONT -dasai-mochi-5x7-medium-r-normal--7-70-75-75-C-50-ISO10646-1")
    out.append("SIZE 7 75 75")
    out.append("FONTBOUNDINGBOX 5 7 0 0")
    out.append("STARTPROPERTIES 2")
    out.append("FONT_ASCENT 7")
    out.append("FONT_DESCENT 0")
    out.append("ENDPROPERTIES")
    out.append(f"CHARS {len(GLYPHS)}")

    def emit(name: str, code: int, rows: list[int]) -> None:
        out.append(f"STARTCHAR {name}")
        out.append(f"ENCODING {code}")
        out.append("SWIDTH 500 0")
        out.append("DWIDTH 6 0")
        out.append("BBX 5 7 0 0")
        out.append("BITMAP")
        for b in rows:
            out.append(f"{b:02X}")
        out.append("ENDCHAR")

    emit("space", 0x20, GLYPHS[" "])
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        emit(ch, ord(ch), GLYPHS[ch])

    out.append("ENDCHARS")
    out.append("ENDFONT")
    return out


def main() -> None:
    print("\n".join(emit_bdf()))


if __name__ == "__main__":
    main()
